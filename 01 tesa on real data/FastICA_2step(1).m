%% step 0
clear; close all; clc;

filepath = 'C:\Users\Utente\OneDrive - Università degli Studi di Milano-Bicocca\unimib\Stage\TMSEEG-tesiLTinfo\01 tesa on real data\';
fileprefix = 'alberto8_tdcs';

% Open EEGLAB
%[ALLEEG EEG CURRENTSET ALLCOM] = eeglab;

%% Step 1: Import data to EEGLAB
filename = [fileprefix, '.set'];
EEG = pop_loadset('filename', filename, 'filepath', filepath);

%% Step 2: Load channel locations (note that you might need to change the file location here for your computer).
EEG = pop_chanedit(EEG, 'lookup','C:\Users\Utente\AppData\Roaming\MathWorks\MATLAB Add-Ons\Collections\eeglab2025.0.0\plugins\dipfit\standard_BESA\standard-10-5-cap385.elp');

%% Step 3: Add TMS pulse events
EEG = pop_chanevent(EEG, 1, ...
    'oper', 'X > 4', ... 
    'edge', 'leading', ...      % extract rising edges (typical for TMS triggers)
    'edgelen', 1, ...           % samples to tolerate for edge detection
    'delevent', 'on', ...       % remove old events
    'nbtype', 1, ...            % treat all triggers as same event type
    'typename', 'TMS', ...      % name the event type
    'delchan', 'on');           % delete the GATE channel

%% Step 4: Remove unused electrodes
EEG = pop_select(EEG, 'nochannel', {'TRIG1' 'TRIG2' 'EOG'});

%Save the original EEG locations for use in interpolation later
EEG.allchan = EEG.chanlocs;

%% Step 5: Remove bad electrodes
EEG = pop_rejchan(EEG, 'elec', [1:size(EEG.data,1)] , ...
    'threshold',7.5, ...
    'norm','on',['' ...
    'measure'],'kurt');

%% Step 6: Downsample data
EEG = pop_resample(EEG, 725);

%% Step 7: Epoch data (-1000 to 1000 ms)
EEG = pop_epoch(EEG, {'TMS'}, [-1 1.00069], 'epochinfo', 'yes');

%% Step 8: Demean data (-1000 ms to 1000 ms)
EEG = pop_rmbase(EEG, [-1000 1000]);

%% Step 9: Remove bad trials (automatic)
EEG = pop_jointprob(EEG,1,[1:size(EEG.data,1)] ,5,5,0,0);
% Automatically identify bad trials based on joint probability
EEG.BadTr = find(EEG.reject.rejjp == 1);
fprintf('Automatically detected %d bad trials\n', length(EEG.BadTr));
EEG = pop_rejepoch(EEG, EEG.BadTr, 0); 

%% Save point
%filename = [fileprefix,'_before.set'];
%EEG = pop_saveset( EEG, 'filename',filename,'filepath',filepath);

%eeglab redraw;

plotAvgTEP(EEG, "Step 9");

%% Step 10: Remove TMS-evoked muscle activity (using FastICA and auto component selection)
EEG = pop_tesa_fastica(EEG, 'approach', 'symm', 'g', 'tanh', 'stabilization', 'off' );
EEG = pop_tesa_compselect(EEG,'comps',15, ...
                              'figSize','small', ...
                              'plotTimeX',[-200 500], ...
                              'plotFreqX',[1 100], ...
                              'tmsMuscle','on', ...
                              'tmsMuscleThresh',8, ...
                              'tmsMuscleWin',[11 30], ...
                              'tmsMuscleFeedback','off', ...
                              'blink','off', ...
                              'blinkThresh',2.5, ...
                              'blinkElecs',{'Fp1','Fp2'}, ...
                              'blinkFeedback','off', ...
                              'move','off', ...
                              'moveThresh',2, ...
                              'moveElecs',{'F7','F8'}, ...
                              'moveFeedback','off', ...
                              'muscle','off', ...
                              'muscleThresh',0.6, ...
                              'muscleFreqWin',[30 100], ...
                              'muscleFeedback','off', ...
                              'elecNoise','off', ...
                              'elecNoiseThresh',4, ...
                              'elecNoiseFeedback','off', ...
                              'remove','on', ...
                              'compCheck','off');

plotAvgTEP(EEG, "Step 10");

%% Step 11: Bandpass (1-48 Hz)
EEG = pop_tesa_filtbutter( EEG, 1, 48, 4, 'bandpass' ); 

plotAvgTEP(EEG, "Step 11");

%% Step 12: Remove all other artifacts (using FastICA and auto component selection)
EEG = pop_tesa_fastica( EEG, 'approach', 'symm', 'g', 'tanh', 'stabilization', 'off' );
EEG = pop_tesa_compselect( EEG,'compCheck','on', ...
                               'comps',[], ...
                               'figSize','small', ...
                               'plotTimeX',[-200 500], ...
                               'plotFreqX',[1 100], ...
                               'tmsMuscle','on', ...
                               'tmsMuscleThresh',8, ...
                               'tmsMuscleWin',[11 30], ...
                               'tmsMuscleFeedback','off', ...
                               'blink','on', ...
                               'blinkThresh',2.5, ...
                               'blinkElecs',{'Fp1','Fp2'}, ...
                               'blinkFeedback','off', ...
                               'move','on', ...
                               'moveThresh',2, ...
                               'moveElecs',{'F7','F8'}, ...
                               'moveFeedback','off', ...
                               'muscle','on', ...
                               'muscleThresh',0.6, ...
                               'muscleFreqIn',[30 100], ...
                               'muscleFeedback','off', ...
                               'elecNoise','on', ...
                               'elecNoiseThresh',4, ...
                               'elecNoiseFeedback','off', ...
                               'remove','on', ...
                               'compCheck','off');

plotAvgTEP(EEG, "Step 12");

%% Step 13: Interpolate missing channels
EEG = pop_interp(EEG, EEG.allchan, 'spherical');

%% Step 14: Re-reference to average
EEG = pop_reref( EEG, []);

plotAvgTEP(EEG, "Step 14");

