%% Remove ocular artifacts using fastICA
function EEG = ICA_OA_rm(EEG)
    % Perform ICA on the EEG data to remove ocular artifacts
    % Input: EEG structure with epoched data
    % Output: EEG structure with ocular artifacts removed
    % Highpass filter before ICA (0.1 Hz)
    EEG = pop_tesa_filtbutter( EEG, 0.1, [], 4, 'highpass' ); 

    % ICA for ocular artifacts
    EEG = pop_tesa_fastica( EEG, 'approach', 'symm', 'g', 'tanh', 'stabilization', 'off' );
    EEG = pop_tesa_compselect(EEG, ...
        'blink','on', ...
        'blinkThresh',2.5, ...
        'blinkFeedback','off', ... 
        'move','on', ...
        'moveThresh',2, ...
        'moveFeedback','off', ... 
        'tmsMuscle','off', ...
        'muscle','off', ...
        'muscleLegacy','off', ...
        'elecNoise','off', ...
        'remove','on', ...
        'compCheck','off', ... 
        'figSize','medium');
end

